import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createRequire } from "node:module";
import { PrismaClient } from "@prisma/client";
import { parseOfficialMedicationFile } from "./v100-official-medication-reimport.mjs";

const require = createRequire(import.meta.url);
const { loadRootEnv } = require("../apps/api/prisma/env");
loadRootEnv();

const prisma = new PrismaClient();
const inbox = resolve("storage/official-medication-sources");
const unsupportedPath = join(inbox, "v101-unsupported-test.txt");
const fixture = resolve("scripts/fixtures/official-medication/nhra-synthetic.csv");
const passes = [];

try {
  await statusWorks();
  await unsupportedFilesAreNotImported();
  syntheticFixtureDryRunWorks();
  applyRequiresExplicitConfirmation();
  noDosingInstructionFieldsGenerated();
  await noFakeOfficialRowsGenerated();
} finally {
  if (existsSync(unsupportedPath)) unlinkSync(unsupportedPath);
  await prisma.$disconnect();
}

for (const pass of passes) console.log(`V101-IMPORT-OPERATOR PASS ${pass}`);
console.log(`V101-IMPORT-OPERATOR SUMMARY PASS ${passes.length} FAIL 0`);

async function statusWorks() {
  const status = runNode(["scripts/v101-official-medication-import-status.mjs"]);
  const parsed = JSON.parse(status.stdout);
  assert.equal(typeof parsed.officialRowCount, "number");
  assert.equal(typeof parsed.inboxFileCount, "number");
  assert.equal(parsed.inboxPath.endsWith("storage\\official-medication-sources") || parsed.inboxPath.endsWith("storage/official-medication-sources"), true);
  passes.push("status works when inbox is empty or populated");
}

async function unsupportedFilesAreNotImported() {
  const before = await officialCount();
  mkdirSync(inbox, { recursive: true });
  writeFileSync(unsupportedPath, "unsupported test artifact; not medication data\n");
  const status = JSON.parse(runNode(["scripts/v101-official-medication-import-status.mjs"]).stdout);
  assert(status.unsupportedFileCount >= 1);
  const after = await officialCount();
  assert.equal(after, before);
  passes.push("unsupported files are counted but not imported");
}

function syntheticFixtureDryRunWorks() {
  const result = runNode(["scripts/v100-official-medication-reimport.mjs", "--source", "NHRA", "--country", "BH", "--file", fixture]);
  const report = extractJson(result.stdout);
  assert.equal(report.mode, "dry-run");
  assert.equal(report.rowsMapped, 2);
  assert.deepEqual(report.countrySource, { country: "BHR", source: "NHRA" });
  assert(report.detectedColumns.includes("Trade Name"));
  assert.equal(report.importedVerificationPolicy.includes("needs_review by default"), true);
  passes.push("synthetic fixture dry-run works with mapping report");
}

function applyRequiresExplicitConfirmation() {
  const result = spawnSync("powershell", [
    "-ExecutionPolicy",
    "Bypass",
    "-File",
    "scripts/v101-official-medication-import-operator.ps1",
    "-Apply",
    "-File",
    fixture,
    "-Source",
    "NHRA",
    "-Country",
    "BH"
  ], {
    cwd: resolve("."),
    env: { ...process.env, APP_ENV: "local" },
    encoding: "utf8"
  });
  assert.notEqual(result.status, 0);
  assert(`${result.stdout}\n${result.stderr}`.includes("Apply requires -ConfirmApply."));
  passes.push("apply requires explicit confirmation");
}

function noDosingInstructionFieldsGenerated() {
  const parsed = parseOfficialMedicationFile({ file: fixture, source: "NHRA", country: "BH" });
  for (const record of parsed.records) {
    assert.equal(Object.prototype.hasOwnProperty.call(record, "dose"), false);
    assert.equal(Object.prototype.hasOwnProperty.call(record, "frequency"), false);
    assert.equal(Object.prototype.hasOwnProperty.call(record, "duration"), false);
    assert.equal(Object.prototype.hasOwnProperty.call(record, "instructions"), false);
    assert.equal(record.isDemo, false);
  }
  passes.push("no dosing instruction fields are generated");
}

async function noFakeOfficialRowsGenerated() {
  const before = await officialCount();
  runNode(["scripts/v100-official-medication-reimport.mjs", "--source", "NHRA", "--country", "BH", "--file", fixture]);
  const after = await officialCount();
  assert.equal(after, before);
  passes.push("no fake official rows are generated by dry-run tooling");
}

async function officialCount() {
  return prisma.drugMarketVariant.count({ where: { isDemo: false } });
}

function runNode(args) {
  const result = spawnSync("node", args, { cwd: resolve("."), encoding: "utf8", env: process.env });
  assert.equal(result.status, 0, `${args.join(" ")} failed\nSTDOUT:\n${result.stdout}\nSTDERR:\n${result.stderr}`);
  return result;
}

function extractJson(stdout) {
  const marker = "{\n";
  const start = stdout.indexOf(marker);
  assert(start >= 0, `No JSON object in output:\n${stdout}`);
  return JSON.parse(stdout.slice(start));
}
